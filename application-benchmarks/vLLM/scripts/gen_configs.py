#!/usr/bin/env python3
"""
Generate the per-(cluster, model) serve-params.json / bench-params.json sweep files.

The benchmark measures a small set of fixed operating points rather than sweeping a curve:
  * serve side:  one entry per parallelism layout, carrying that layout's max batch size N
  * bench side:  each operating point x each of the 2 fixed workload shapes

DeepSeek-V4-Pro is the only scored model; it uses a native FP4+FP8 mixed checkpoint
(deepseek-ai/DeepSeek-V4-Pro). Llama-3.3-70B and GPT-OSS-120B remain here, unscored and not
generated by default, purely so the harness can be smoke-tested on a single node — DeepSeek
needs ~16 GPUs to run at all. Generate them explicitly with --only-model.

Parallelism is per cluster because it depends on GPUs/node and GPU memory. DeepSeek-V4-Pro
(~1.6T) needs ~16 GPUs: on 4-GPU nodes (the Snellius H100 example) that is TP=4 within a node
plus PP=4 across nodes (served via Ray); on 8-GPU nodes it is TP=8 on a single node.

N (the max batch size, `max_num_seqs`) is declared per layout and is vendor-tunable. To find it,
start the layout once and read vLLM's own startup line:

    Maximum concurrency for 9216 tokens per request: X.XXx

then use that value, or the nearest lower power of two. One N covers both shapes: they each sum
to 9216 = --max-model-len, so peak KV per sequence is identical.

This script IS the canonical way to (re)author configs — edit MODELS / CLUSTERS / SHAPES /
POINTS below and re-run. Output paths: configs/<cluster>/<model>/{serve,bench}-params.json

Usage:
    python scripts/gen_configs.py            # write all clusters, scored models only
    python scripts/gen_configs.py --cluster snellius/h100
    python scripts/gen_configs.py --only-model gpt-oss-120b --profile debug
"""
import argparse
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# Fixed workload shapes (input_len, output_len). Both sum to 9216 = --max-model-len, which is
# why a single N per layout is valid for both (see module docstring).
SHAPES = [(1024, 8192), (8192, 1024)]

# Operating points, as a fraction of the layout's max batch size N (`max_num_seqs`), or as an
# absolute concurrency. NOTHING in the code may assume how many points there are: dropping a
# point should mean deleting a row here and the matching row of the table under "Operating
# points" in README.md (the spec has to state what is measured). tests/test_points.py enforces
# that those two stay in sync, and that nothing else encodes the count.
POINTS = [
    {"label": "low",  "abs":  1},
    {"label": "mid",  "frac": 0.5},
    {"label": "high", "frac": 1.0},
]

# Prompt counts of the hosted dataset files (the _n<N> filename suffix). Each run needs
# num_prompts = 2 x max_concurrency, so the smallest file covering that is selected.
DATASET_SIZES = [1024, 32768, 131072]

# Reduced sweeps for pipeline sanity-checks. Slices are applied to POINTS / SHAPES / the model's
# parallels list; `parallels` picks the largest single-node layout for the dense models, which is
# much faster to load than TP=1. Non-`full` profiles write to a suffixed cluster dir.
PROFILES = {
    "full":  {"points": slice(None),   "shapes": slice(None),  "parallels": slice(None)},
    "debug": {"points": slice(0, 1),   "shapes": slice(0, 1),  "parallels": slice(-1, None)},
    "small": {"points": slice(None),   "shapes": slice(0, 1),  "parallels": slice(-1, None)},
}


def _resolve_point(point: dict, n: int) -> int:
    """Concurrency for one operating point at max batch size `n`."""
    if "abs" in point:
        return int(point["abs"])
    return max(1, int(n * point["frac"]))


def _dataset_size(num_prompts: int) -> int:
    """Smallest hosted dataset that holds `num_prompts` prompts."""
    for size in DATASET_SIZES:
        if size >= num_prompts:
            return size
    raise ValueError(
        f"No hosted dataset holds {num_prompts} prompts (largest is {DATASET_SIZES[-1]}). "
        f"Lower max_num_seqs or have the organisers publish a larger file."
    )


def _serve_entries(model: str, extra: dict, parallels: list[dict]) -> list[dict]:
    """One entry per layout. `max_num_seqs` (N) comes from the layout itself."""
    return [{"model": model, **extra, **par} for par in parallels]


def _bench_entries(model: str, dataset_prefix: str, parallels: list[dict],
                   points: list[dict], shapes: list[tuple[int, int]]) -> list[dict]:
    """One entry per (distinct N, point, shape).

    Operating points are fractions of N, so a layout's benches are only valid for layouts with
    the same N. Each entry therefore carries `_n`, and the orchestrator links serve to bench on
    `model` *and* `max_num_seqs=_n` — otherwise a TP4 layout would also be benched at a TP8
    layout's concurrencies. Layouts sharing an N share their bench entries.
    """
    out: list[dict] = []
    for n in sorted({par["max_num_seqs"] for par in parallels}):
        seen: set[int] = set()
        for point in points:
            concurrency = _resolve_point(point, n)
            if concurrency in seen:
                # e.g. N=2 puts the N/2 point on top of the absolute-1 point: keep the first.
                print(f"    note: point '{point['label']}' collapses onto concurrency "
                      f"{concurrency} at N={n} — skipping the duplicate")
                continue
            seen.add(concurrency)
            num_prompts = 2 * concurrency
            for in_len, out_len in shapes:
                stem = f"{dataset_prefix}_i{in_len}_o{out_len}_n{_dataset_size(num_prompts)}"
                out.append({
                    "model": model,
                    "_point": point["label"],
                    "_n": n,
                    "max_concurrency": concurrency,
                    "num_prompts": num_prompts,
                    "dataset-path": f"/dev/shm/{stem}.jsonl",
                    "custom-output-len": out_len,
                })
    return out


# Per-model definitions shared across clusters. `parallels` may be overridden per cluster (see
# CLUSTERS); `extra` are constant serve flags appended to every entry. `scored` marks the models
# that are part of the benchmark — the others exist only as single-node smoke tests.
MODELS = {
    "deepseek-v4-pro": {
        "model": "deepseek-ai/DeepSeek-V4-Pro",
        "dataset_prefix": "dsv4",
        "scored": True,
        # Native FP4+FP8 mixed checkpoint. trust-remote-code + tokenizer-mode are required to
        # load it; expert-parallel is the MoE layout over the TP×PP world. These are universal;
        # per-cluster tunables (parallelism layout, N, and any compilation flags) live in CLUSTERS.
        "extra": {"trust-remote-code": True, "tokenizer-mode": "deepseek_v4",
                  "enable-expert-parallel": True},
        # `parallels` is cluster-specific (GPU memory / GPUs-per-node) — see CLUSTERS.
        "parallels": None,
    },
    # ── unscored: single-node smoke tests for the harness itself ──────────────────────────────
    "llama-70b-fp8": {
        "model": "nvidia/Llama-3.3-70B-Instruct-FP8",
        "dataset_prefix": "llama70b",
        "scored": False,
        "extra": {},  # FP8 precision is encoded in the checkpoint; vLLM auto-detects it.
        "parallels": [{"tensor-parallel-size": 1, "max_num_seqs": 64},
                      {"tensor-parallel-size": 2, "max_num_seqs": 128},
                      {"tensor-parallel-size": 4, "max_num_seqs": 256}],
    },
    "gpt-oss-120b": {
        "model": "openai/gpt-oss-120b",
        "dataset_prefix": "gpt120b",
        "scored": False,
        "extra": {},  # native MXFP4 weights; no quantization flag
        "parallels": [{"tensor-parallel-size": 1, "max_num_seqs": 64},
                      {"tensor-parallel-size": 2, "max_num_seqs": 128},
                      {"tensor-parallel-size": 4, "max_num_seqs": 256}],
    },
}

# Cluster-specific overrides (per-platform: GPU count/memory, N, and any compilation tunables).
# `extra` here is *merged into* the model's base extra; other keys replace. An 8-GPU single-node
# DeepSeek layout (TP8) is documented in the README; uncomment the example to author such a config.
CLUSTERS = {
    "snellius/h100": {           # 4 × 94GiB H100 per node
        "deepseek-v4-pro": {
            # max_num_seqs is this layout's max batch size N — vendor-tunable, one per layout.
            # Add further dicts here to submit additional layouts; their cells are pooled.
            "parallels": [{"tensor-parallel-size": 4, "pipeline-parallel-size": 4,
                           "max_num_seqs": 32}],
            # _extra_serve_args is appended verbatim to `vllm serve` (keys starting with `_` are
            # skipped by apply_params_to_cmd / combo_subdir): the dotted -cc.* compilation flags
            # can't go through the --key=value builder, and DeepSeek-V4's default compilation
            # crashes on this TP4×PP4 layout — full torch.compile (mode=3) with a decode-only
            # CUDA-graph capture is required here. Per-platform tunable, so it lives per-cluster.
            "extra": {"_extra_serve_args": "-cc.mode=3 -cc.cudagraph_mode=FULL_DECODE_ONLY"},
        },
    },
    # Two MI355X variants, differing only in N (max_num_seqs) and the GPU_MEM_UTIL that makes
    # that N reachable. N is a declared, self-policed submission parameter, so the choice is a
    # measurement, not a preference: at GPU_MEM_UTIL=0.90 the TP8 engine reports
    #     GPU KV cache size: 263,820 tokens, Maximum concurrency for 9,216 tokens: 28.63x
    # which does not cover a concurrency-32 high point. mi355x therefore declares the nearest
    # lower power of two; mi355x-n32 buys the headroom back with VRAM (0.97 -> 32.61x, the
    # first value with real margin — see that cluster's system.sh for the measured table).
    # Run both and submit whichever scores higher: they are alternative operating envelopes
    # for the same layout, not a fallback and a primary.
    "amd/mi355x": {            # 8 x 288GiB MI355X per node, N=16 @ GPU_MEM_UTIL=0.90
        "deepseek-v4-pro": {
            # 2.3 TiB of HBM per node holds the ~806 GiB checkpoint outright, so the scored
            # layout is TP8 inside a single node — no PP, no Ray, no second node.
            "parallels": [{"tensor-parallel-size": 8, "max_num_seqs": 16}],
            # No _extra_serve_args: the -cc.* overrides on snellius/h100 exist because
            # DeepSeek-V4's default compilation crashes on *that* TP4xPP4 layout. Leave the
            # ROCm TP8 path on vLLM's defaults; if the engine dies during startup, adding
            # "_extra_serve_args": "-cc.mode=3 -cc.cudagraph_mode=FULL_DECODE_ONLY" here is
            # the first thing to try.
        },
    },
    "amd/mi355x-n32": {        # same node, N=32 @ GPU_MEM_UTIL=0.97 (see configs/.../system.sh)
        "deepseek-v4-pro": {
            "parallels": [{"tensor-parallel-size": 8, "max_num_seqs": 32}],
        },
    },
    # Identical to mi355x-n32 except for the CHECKPOINT: amd/DeepSeek-V4-Pro-MXFP4 declares
    # MXFP4 activations, so the routed experts run W4A4 on the FP4 matrix cores instead of the
    # base checkpoint's W4A8. Same engine, same layout, same N — the delta isolates activation
    # precision. NOT SUBMITTABLE (README §8.5 bars additional activation quantisation, §3/§8.1
    # pin the checkpoint); see that cluster's system.sh.
    "amd/mi355x-n32-w4a4": {
        "deepseek-v4-pro": {
            "model": "amd/DeepSeek-V4-Pro-MXFP4",
            "parallels": [{"tensor-parallel-size": 8, "max_num_seqs": 32}],
        },
    },
    # Identical to mi355x-n32 except for the engine version (v0.23.0 vs the pinned v0.29.0),
    # so the delta isolates vLLM itself. NOT SUBMITTABLE — README §9 ruling 10 invalidates a
    # submission on a different version; see that cluster's system.sh.
    "amd/mi355x-n32-v023": {
        "deepseek-v4-pro": {
            "parallels": [{"tensor-parallel-size": 8, "max_num_seqs": 32}],
        },
    },
}


def write_model(cluster: str, model_key: str, profile: str) -> None:
    spec = dict(MODELS[model_key])
    override = CLUSTERS[cluster].get(model_key, {})
    # Merge `extra` (cluster extra augments the model's base extra); other keys replace.
    merged_extra = {**spec.get("extra", {}), **override.get("extra", {})}
    spec.update(override)
    spec["extra"] = merged_extra
    if spec["parallels"] is None:
        raise ValueError(f"{model_key} has no parallels for cluster {cluster}")

    p = PROFILES[profile]
    parallels = spec["parallels"][p["parallels"]]
    points = POINTS[p["points"]]
    shapes = SHAPES[p["shapes"]]

    missing = [par for par in parallels if "max_num_seqs" not in par]
    if missing:
        raise ValueError(
            f"{cluster}/{model_key}: every parallels entry needs a max_num_seqs (the layout's "
            f"max batch size N); missing in {missing}"
        )

    # Non-`full` profiles go to a suffixed cluster dir (e.g. snellius/h100-debug) so the
    # orchestrator's */{serve,bench}-params.json glob sees only the reduced sweep.
    out_cluster = cluster if profile == "full" else f"{cluster}-{profile}"
    out_dir = REPO_ROOT / "configs" / out_cluster / model_key
    out_dir.mkdir(parents=True, exist_ok=True)

    serve = _serve_entries(spec["model"], spec["extra"], parallels)
    bench = _bench_entries(spec["model"], spec["dataset_prefix"], parallels, points, shapes)

    (out_dir / "serve-params.json").write_text(json.dumps(serve, indent=2) + "\n")
    (out_dir / "bench-params.json").write_text(json.dumps(bench, indent=2) + "\n")
    jobs = sum(1 for s in serve for b in bench if s["max_num_seqs"] == b["_n"])
    print(f"  {out_cluster}/{model_key}: {len(serve)} layout(s), {len(bench)} bench entries "
          f"→ {jobs} jobs")

    # Suffixed clusters inherit the base cluster's system.sh (partition, container, GPUs/node).
    if profile != "full":
        sys_link = REPO_ROOT / "configs" / out_cluster / "system.sh"
        if not sys_link.is_symlink() and not sys_link.exists():
            sys_link.symlink_to(Path("..") / Path(cluster).name / "system.sh")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cluster", default=None,
                    help="Only this cluster (e.g. snellius/h100). Default: all.")
    ap.add_argument("--profile", default="full", choices=list(PROFILES),
                    help="full = the real benchmark; debug/small = reduced sanity sweeps written "
                         "to configs/<cluster>-<profile>/ (default: full).")
    ap.add_argument("--only-model", default=None, choices=list(MODELS),
                    help="Generate just this one model. Default: every scored model. The unscored "
                         "smoke-test models can only be generated this way.")
    args = ap.parse_args()

    clusters = [args.cluster] if args.cluster else list(CLUSTERS)
    model_keys = ([args.only_model] if args.only_model
                  else [k for k, v in MODELS.items() if v["scored"]])
    for cluster in clusters:
        if cluster not in CLUSTERS:
            raise SystemExit(f"Unknown cluster {cluster}; known: {list(CLUSTERS)}")
        print(f"{cluster} (profile={args.profile}):")
        for model_key in model_keys:
            write_model(cluster, model_key, args.profile)


if __name__ == "__main__":
    main()
